%% ============================================================
% RADIAL RIEMANN-INVARIANT BUFFER BOUNDARY ILLUSTRATION
% Matches the radial particle structure used in the C++ solver
% ============================================================

%% ------------------------------------------------------------
% Solver geometry / parameters
% ------------------------------------------------------------

PI = pi;

Dcylinder = 0.1;
r0 = 0.5*Dcylinder;

R = 10*Dcylinder;

dr0 = Dcylinder/10.0;

Nr = 50;
Nbuffer = 8;
NrTotal = Nr + Nbuffer;

NsupportLayers = 3;

gammaEOS = 7.0;
rho0 = 1000.0;

inletVelocity = 0.1;
flowAngle = 0.0;

inletVelocityX = ...
    inletVelocity*cos(flowAngle);

inletVelocityY = ...
    inletVelocity*sin(flowAngle);

c0 = 20.0*inletVelocity;


%% ============================================================
% Radial stretching: same logic as C++ solver
% ============================================================

target = (R-r0)/dr0;

radialSum = @(qA,N) ...
    (abs(qA-1.0)<1e-12).*N ...
    + ...
    (abs(qA-1.0)>=1e-12) ...
    .*((qA.^N-1.0)./(qA-1.0));

qAlow = 0.0;
qAhigh = 2.0;

maxiter = 1000;
tolerance = 1.0e-6;

qA = 1.0;

for iter = 1:maxiter

    qAmid = ...
        0.5*(qAlow+qAhigh);

    errorQ = ...
        radialSum(qAmid,Nr) ...
        - target;

    if abs(errorQ) < tolerance
        qA = qAmid;
        break;
    end

    if radialSum(qAmid,Nr) < target
        qAlow = qAmid;
    else
        qAhigh = qAmid;
    end

    qA = qAmid;
end

Apolar = log(qA);

Bpolar = ...
    dr0/(qA-1.0);


%% ============================================================
% Angular discretisation
% ============================================================

NTheta = ...
    round(2*PI*r0/dr0);

dTheta0 = ...
    2*PI/NTheta;

thetaList = ...
    (0:NTheta-1)*dTheta0;


%% ============================================================
% Radial particle-ring positions
%
% ir = 0                cylinder wall
% ir = 1 ... Nr         physical fluid
% ir = Nr+1 ... NrTotal buffer
% ============================================================

rRings = ...
    zeros(NrTotal+1,1);

rRings(1) = r0;

for ir = 1:NrTotal

    rRings(ir+1) = ...
        Bpolar*(qA^ir-1.0) ...
        + r0;

end


%% ============================================================
% Important radii
% ============================================================

rFirstFluid = ...
    rRings(2);

rInterface = ...
    rRings(Nr+1);

rFirstBuffer = ...
    rRings(Nr+2);

rLastBuffer = ...
    rRings(NrTotal+1);


%% ============================================================
% Support rings
%
% Support layers are mirrored from corresponding outer
% fluid rings across r = r0
% ============================================================

supportRings = [];

for layer = 1:NsupportLayers

    rFluid = ...
        rRings(layer+1);

    rSupport = ...
        2.0*r0-rFluid;

    if rSupport > 0.0

        supportRings(end+1) = ...
            rSupport; %#ok<SAGROW>

    end
end


